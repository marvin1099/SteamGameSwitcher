"""Linux desktop launcher integration."""

from __future__ import annotations

import os
import shutil
import sys
import tempfile
from collections.abc import Sequence
from pathlib import Path

DESKTOP_FILE_NAME = "steam-game-switcher"
DESKTOP_ENTRY_NAME = f"{DESKTOP_FILE_NAME}.desktop"
_MANAGED_MARKER = "# Generated by Steam Game Switcher"


def application_icon_path() -> Path:
    """Return the installed SVG application icon."""
    return Path(__file__).parent / "assets" / "steam-game-switcher.svg"


def applications_directory() -> Path:
    """Return the user-level applications menu directory on Linux."""
    configured_data_home = os.environ.get("XDG_DATA_HOME")
    data_home = (
        Path(configured_data_home).expanduser()
        if configured_data_home
        else Path.home() / ".local" / "share"
    )
    if not data_home.is_absolute():
        data_home = Path.home() / ".local" / "share"
    return data_home / "applications"


def _desktop_argument(value: str) -> str:
    if any(character in value for character in "\0\r\n"):
        raise ValueError("Desktop launcher arguments cannot contain newlines or NUL characters.")
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'"{escaped}"'


def render_application_desktop_entry(
    command: Sequence[str],
    icon_path: Path | None = None,
) -> str:
    """Render the Linux app-menu entry for the GUI."""
    if not command:
        raise ValueError("Desktop launcher command cannot be empty.")
    icon = (icon_path or application_icon_path()).expanduser().resolve()
    command = " ".join(_desktop_argument(argument) for argument in command)
    return "\n".join(
        (
            "[Desktop Entry]",
            _MANAGED_MARKER,
            "Version=1.0",
            "Type=Application",
            "Name=Steam Game Switcher",
            "Comment=Switch Steam branches and manage game backups",
            f"Exec={command}",
            f"Icon={icon}",
            "Terminal=false",
            "Categories=Game;Utility;",
            f"StartupWMClass={DESKTOP_FILE_NAME}",
            "",
        )
    )


def install_application_desktop_entry() -> Path | None:
    """Install or refresh SGS's user-level Linux app-menu entry without clobbering user files."""
    if sys.platform != "linux":
        return None

    sgs_executable = shutil.which("sgs")
    command = (
        [sgs_executable, "gui"]
        if sgs_executable
        else [sys.executable, "-m", "steam_game_switcher", "gui"]
    )
    contents = render_application_desktop_entry(command)
    applications = applications_directory()
    destination = applications / DESKTOP_ENTRY_NAME

    if destination.exists():
        try:
            existing = destination.read_text(encoding="utf-8")
        except OSError:
            return None
        if _MANAGED_MARKER not in existing:
            return None
        if existing == contents:
            return destination

    temporary_path: Path | None = None
    try:
        applications.mkdir(parents=True, exist_ok=True)
        file_descriptor, temporary_name = tempfile.mkstemp(
            prefix=f".{destination.name}.", suffix=".tmp", dir=applications
        )
        temporary_path = Path(temporary_name)
        with os.fdopen(file_descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
        temporary_path.chmod(0o755)
        os.replace(temporary_path, destination)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    return destination
